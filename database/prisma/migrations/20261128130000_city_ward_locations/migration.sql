-- Two-level administrative units (in force since 1 July 2025): City -> Ward.
-- Districts no longer exist, so DISTRICTS / DISTRICT_NEIGHBORS and every district
-- column go away. LOCATIONS now holds every ward, commune and special zone of
-- Ho Chi Minh City and Ha Noi, keyed by the official ward code (same id on every
-- database branch). Source list: src/shared/administrativeUnits.json.
-- USERS gets a private street address; TASKS gets isApproximateLocation, set when the
-- requester posts a nearby address because their own house cannot be geocoded.

-- Old text -> FK sync triggers (they read LOCATIONS.ward and DISTRICTS) ----------
