CREATE TABLE "SUPPORT_TICKETS" (
  "id" SERIAL PRIMARY KEY,
  "category" TEXT NOT NULL,
  "subject" TEXT NOT NULL,
  "description" TEXT NOT NULL,
  "status" TEXT NOT NULL DEFAULT 'OPEN',
  "priority" TEXT NOT NULL DEFAULT 'NORMAL',
  "evidenceUrls" TEXT[] DEFAULT ARRAY[]::TEXT[],
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  "resolvedAt" TIMESTAMP(3),
  "closedAt" TIMESTAMP(3),
  "requesterId" INTEGER NOT NULL,
  "taskId" INTEGER,
  "paymentId" INTEGER,
  CONSTRAINT "SUPPORT_TICKETS_category_check" CHECK ("category" IN ('TASK','BIDDING','PAYMENT','ACCOUNT','TECHNICAL','OTHER')),
  CONSTRAINT "SUPPORT_TICKETS_status_check" CHECK ("status" IN ('OPEN','IN_PROGRESS','RESOLVED','CLOSED')),
  CONSTRAINT "SUPPORT_TICKETS_priority_check" CHECK ("priority" IN ('LOW','NORMAL','HIGH','URGENT'))
);
CREATE INDEX "SUPPORT_TICKETS_requesterId_createdAt_idx" ON "SUPPORT_TICKETS"("requesterId", "createdAt");
CREATE INDEX "SUPPORT_TICKETS_status_category_priority_createdAt_idx" ON "SUPPORT_TICKETS"("status", "category", "priority", "createdAt");

CREATE TABLE "SUPPORT_MESSAGES" (
  "id" SERIAL PRIMARY KEY,
  "ticketId" INTEGER NOT NULL,
  "senderId" INTEGER NOT NULL,
  "body" TEXT NOT NULL,
  "evidenceUrls" TEXT[] DEFAULT ARRAY[]::TEXT[],
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "SUPPORT_MESSAGES_ticketId_createdAt_idx" ON "SUPPORT_MESSAGES"("ticketId", "createdAt");

CREATE TABLE "SUPPORT_ACTIVITIES" (
  "id" SERIAL PRIMARY KEY,
  "ticketId" INTEGER NOT NULL,
  "actorId" INTEGER NOT NULL,
  "action" TEXT NOT NULL,
  "fromValue" TEXT,
  "toValue" TEXT,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "SUPPORT_ACTIVITIES_ticketId_createdAt_idx" ON "SUPPORT_ACTIVITIES"("ticketId", "createdAt");

